// Generates out/sw.js: an offline-first service worker (Part J5).
// App shell + manifest + listings are precached; question/answer files are cached
// as they are opened (and all at once via Settings → "Make all content available offline").
import { createHash } from "node:crypto";
import { readdirSync, statSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";

const out = path.resolve(import.meta.dirname, "..", "out");
const base = process.env.NEXT_PUBLIC_BASE_PATH ?? "";
if (!existsSync(out)) throw new Error("out/ missing — run next build first");

const files = [];
(function walk(dir) {
  for (const f of readdirSync(dir)) {
    const p = path.join(dir, f);
    if (statSync(p).isDirectory()) walk(p);
    else files.push(path.relative(out, p).split(path.sep).join("/"));
  }
})(out);

const precache = files
  .filter((f) => !f.startsWith("content/q/") && !f.startsWith("content/a/") && !f.endsWith(".txt") && f !== "sw.js" && !f.endsWith(".map"))
  .map((f) => `${base}/${f.replace(/index\.html$/u, "")}`);
const version = createHash("sha256").update(files.map((f) => f + statSync(path.join(out, f)).size).join("|")).digest("hex").slice(0, 12);

const sw = `// Generated by scripts/build-sw.mjs — do not edit.
const VERSION = ${JSON.stringify(version)};
const SHELL = "cusp-shell-" + VERSION;
const CONTENT = "cusp-content";
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(SHELL).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("cusp-shell-") && k !== SHELL).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("message", (e) => {
  if (e.data && e.data.type === "cache-urls") {
    e.waitUntil(caches.open(CONTENT).then((c) => c.addAll(e.data.urls)).then(() => e.source && e.source.postMessage({ type: "cache-done", count: e.data.urls.length })));
  }
});
self.addEventListener("fetch", (e) => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== "GET" || url.origin !== self.location.origin) return;
  const isContent = url.pathname.includes("/content/");
  const isNavigation = req.mode === "navigate";
  const save = async (res) => {
    if (res && res.ok) (await caches.open(isContent ? CONTENT : SHELL)).put(req, res.clone());
    return res;
  };
  if (isNavigation) {
    // Pages: network first so a new deploy shows up immediately; cache when offline.
    e.respondWith(fetch(req).then(save).catch(async () => (await caches.match(req, { ignoreSearch: true })) || (await caches.match(${JSON.stringify(`${base}/app/`)})) || new Response("Offline", { status: 503 })));
    return;
  }
  if (isContent) {
    // Content JSON: network first (revalidated past the HTTP cache) so a new publish
    // shows up on the next load; fall back to the cached copy when offline or slow.
    e.respondWith((async () => {
      try {
        const res = await Promise.race([
          fetch(req, { cache: "no-cache" }),
          new Promise((_, reject) => setTimeout(() => reject(new Error("timeout")), 4000)),
        ]);
        if (res.ok) return await save(res);
        return (await caches.match(req)) || res;
      } catch {
        return (await caches.match(req)) || new Response("Offline", { status: 503, headers: { "content-type": "text/plain" } });
      }
    })());
    return;
  }
  // Hashed app assets: cache first, refresh in the background.
  e.respondWith((async () => {
    const cached = await caches.match(req);
    const network = fetch(req).then(save).catch(() => undefined);
    if (cached) { e.waitUntil(network); return cached; }
    return (await network) || new Response("Offline", { status: 503, headers: { "content-type": "text/plain" } });
  })());
});
`;
writeFileSync(path.join(out, "sw.js"), sw);
writeFileSync(path.join(out, ".nojekyll"), "");
console.log(`✓ service worker ${version}: ${precache.length} files precached`);
